export interface LawMeta {
  id: string;
  tab: string;
  name: string;
  short: string;
}

export interface Heading {
  h: number;
  l: string;
  n: string;
  id: string;
  a?: string[];
}
export interface Para {
  t: string;
  n?: string[];
  r?: 1;
}
export interface Article {
  k: string;
  p: Para[];
  rb?: string;
  r?: 1;
}
export type LawItem = Heading | Article;

export interface LawData {
  id: string;
  title: string;
  url: string;
  fetched: string;
  items: LawItem[];
}

export const isHeading = (it: LawItem): it is Heading => "h" in it;

// The catalog bundled with the app is generated by scripts/laws/build-laws.mjs. Law updates downloaded
// at run time (src/updates.ts) can replace it, so LAWS and TABS are filled in place by applyCatalog.
import bundled from "../public/data/laws.json";

export interface CatalogEntry {
  id: string;
  tab: string;
  short: string;
  topic: string;
  title: string;
  articles: number;
  maxArt?: number;
  hash?: string;
  updated?: string;
}
export const BUNDLED_CATALOG = bundled as CatalogEntry[];

export const LAWS: LawMeta[] = [];
/** Tabs in catalog order: the codes first, then the areas of special legislation. */
export const TABS: string[] = [];
export function applyCatalog(entries: CatalogEntry[]): void {
  LAWS.splice(0, LAWS.length, ...entries.map((l) => ({ id: l.id, tab: l.tab, name: l.topic, short: l.short })));
  TABS.splice(0, TABS.length, ...new Set(LAWS.map((l) => l.tab)));
}
applyCatalog(BUNDLED_CATALOG);

export const lawsInTab = (tab: string): LawMeta[] => LAWS.filter((l) => l.tab === tab);
export const lawMeta = (id: string): LawMeta => LAWS.find((l) => l.id === id) ?? LAWS[0];
